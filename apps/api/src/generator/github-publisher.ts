import { createAppAuth, type StrategyOptions } from '@octokit/auth-app'

interface PublishResult {
  repoUrl: string
  repoOwner: string
  installCommand: string
}

interface PublishFile {
  path: string
  content: string
  encoding?: 'base64'
}

interface PublishOptions {
  userName: string
  files: PublishFile[]
  githubAccessToken?: string
}

async function getInstallationToken(): Promise<string> {
  const appId = process.env.GITHUB_APP_ID
  const privateKeyBase64 = process.env.GITHUB_APP_PRIVATE_KEY
  const installationId = process.env.GITHUB_APP_INSTALLATION_ID

  const missing = [
    !appId && 'GITHUB_APP_ID',
    !privateKeyBase64 && 'GITHUB_APP_PRIVATE_KEY',
    !installationId && 'GITHUB_APP_INSTALLATION_ID',
  ].filter(Boolean)

  if (missing.length) {
    throw new Error(`GitHub App env vars missing: ${missing.join(', ')}`)
  }

  console.log(`[github] Requesting installation token — appId=${appId}, installationId=${installationId}`)

  const privateKey = Buffer.from(privateKeyBase64!, 'base64').toString('utf-8')

  try {
    const auth = createAppAuth({
      appId: Number(appId),
      privateKey,
      installationId: Number(installationId),
    })

    const { token } = await auth({ type: 'installation' })
    console.log('[github] Installation token acquired')
    return token
  } catch (err: unknown) {
    const e = err as { status?: number; response?: { data?: unknown; url?: string } }
    console.error('[github] Token request failed:', {
      status: e.status,
      url: e.response?.url,
      data: e.response?.data,
      message: err instanceof Error ? err.message : String(err),
    })
    throw new Error(
      `GitHub App auth failed (HTTP ${e.status ?? '?'}): installation ${installationId} — check GITHUB_APP_INSTALLATION_ID and that the app is installed on the org`
    )
  }
}

export async function listAppInstallations(): Promise<unknown> {
  const appId = process.env.GITHUB_APP_ID
  const privateKeyBase64 = process.env.GITHUB_APP_PRIVATE_KEY

  if (!appId || !privateKeyBase64) {
    return { error: 'Missing GITHUB_APP_ID or GITHUB_APP_PRIVATE_KEY' }
  }

  const privateKey = Buffer.from(privateKeyBase64, 'base64').toString('utf-8')

  const auth = createAppAuth({ appId: Number(appId), privateKey } as StrategyOptions)
  const { token } = await auth({ type: 'app' })

  const res = await fetch('https://api.github.com/app/installations', {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
  })
  const data = await res.json()

  // Also fetch the app info to get the slug
  const appRes = await fetch('https://api.github.com/app', {
    headers: { Authorization: `Bearer ${token}`, Accept: 'application/vnd.github+json' },
  })
  const appData = await appRes.json() as { slug?: string; html_url?: string; name?: string }

  if (!res.ok) return { status: res.status, error: data }

  return {
    app: { slug: appData.slug, name: appData.name, installUrl: `https://github.com/apps/${appData.slug}/installations/new` },
    installations: (data as Array<{ id: number; account: { login: string }; target_type: string }>).map(
    (i) => ({ id: i.id, account: i.account?.login, targetType: i.target_type })
  ),
  }
}

async function publishToOrgRepo(
  repoName: string,
  files: PublishFile[]
): Promise<PublishResult> {
  const token = await getInstallationToken()
  const orgName = process.env.GITHUB_ORG_NAME || 'skill-builder-agent'

  console.log(`[github] Publishing to org repo: ${orgName}/${repoName} (${files.length} files)`)

  const checkRes = await fetch(`https://api.github.com/repos/${orgName}/${repoName}`, {
    headers: { Authorization: `Bearer ${token}` },
  })
  const repoExists = checkRes.ok

  if (!repoExists) {
    console.log(`[github] Repo not found (${checkRes.status}), creating ${orgName}/${repoName}`)
    const createRes = await fetch(`https://api.github.com/orgs/${orgName}/repos`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        name: repoName,
        description: 'Professional identity skill generated by actingas.me',
        private: false,
        auto_init: true,
      }),
    })
    if (!createRes.ok) {
      const err = await createRes.json().catch(() => ({}))
      console.error(`[github] Org repo creation failed: ${createRes.status}`, err)
      throw new Error(`Failed to create org repo: ${createRes.status} — ${JSON.stringify(err)}`)
    }
    console.log(`[github] Repo created, waiting for init`)
    await new Promise((r) => setTimeout(r, 2000))
  } else {
    console.log(`[github] Repo exists, updating files`)
  }

  for (const file of files) {
    const existingRes = await fetch(
      `https://api.github.com/repos/${orgName}/${repoName}/contents/${file.path}`,
      { headers: { Authorization: `Bearer ${token}` } }
    )
    const existing = existingRes.ok ? await existingRes.json() : null

    const putRes = await fetch(
      `https://api.github.com/repos/${orgName}/${repoName}/contents/${file.path}`,
      {
        method: 'PUT',
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          message: `Update ${file.path}`,
          content: file.encoding === 'base64'
            ? file.content
            : Buffer.from(file.content, 'utf-8').toString('base64'),
          sha: existing?.sha,
        }),
      }
    )
    if (!putRes.ok) {
      const err = await putRes.json().catch(() => ({}))
      console.error(`[github] File push failed for ${file.path}: ${putRes.status}`, err)
    } else {
      console.log(`[github] Pushed ${file.path}`)
    }
  }

  console.log(`[github] Publish complete: ${orgName}/${repoName}`)
  return {
    repoUrl: `https://github.com/${orgName}/${repoName}`,
    repoOwner: orgName,
    installCommand: `npx skills install ${orgName}/${repoName}`,
  }
}

export async function publishToGitHub(options: PublishOptions): Promise<PublishResult> {
  const { userName, files, githubAccessToken } = options
  const slug = userName.toLowerCase().replace(/\s+/g, '-')
  const repoName = `acting-as-${slug}`

  if (githubAccessToken) {
    return publishToPersonalRepo(repoName, files, githubAccessToken)
  }

  return publishToOrgRepo(repoName, files)
}

async function publishToPersonalRepo(
  repoName: string,
  files: PublishFile[],
  token: string
): Promise<PublishResult> {
  const userRes = await fetch('https://api.github.com/user', {
    headers: { Authorization: `Bearer ${token}` },
  })
  const user = await userRes.json()
  const owner = user.login

  let repoExists = false
  const checkRes = await fetch(`https://api.github.com/repos/${owner}/${repoName}`, {
    headers: { Authorization: `Bearer ${token}` },
  })
  repoExists = checkRes.ok

  if (!repoExists) {
    const createRes = await fetch('https://api.github.com/user/repos', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        name: repoName,
        description: `Professional identity skill generated by actingas.me`,
        private: false,
        auto_init: true,
      }),
    })
    if (!createRes.ok) {
      const err = await createRes.json().catch(() => ({}))
      console.error('GitHub repo creation failed:', createRes.status, err)
      throw new Error(`Failed to create repo: ${createRes.status}`)
    }
    // Wait for GitHub to initialize the repo
    await new Promise((r) => setTimeout(r, 2000))
  }

  for (const file of files) {
    const existingRes = await fetch(
      `https://api.github.com/repos/${owner}/${repoName}/contents/${file.path}`,
      { headers: { Authorization: `Bearer ${token}` } }
    )
    const existing = existingRes.ok ? await existingRes.json() : null

    const putRes = await fetch(
      `https://api.github.com/repos/${owner}/${repoName}/contents/${file.path}`,
      {
        method: 'PUT',
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          message: `Update ${file.path}`,
          content: file.encoding === 'base64'
            ? file.content
            : Buffer.from(file.content, 'utf-8').toString('base64'),
          sha: existing?.sha,
        }),
      }
    )
    if (!putRes.ok) {
      const err = await putRes.json().catch(() => ({}))
      console.error(`GitHub file push failed for ${file.path}:`, putRes.status, err)
    }
  }

  return {
    repoUrl: `https://github.com/${owner}/${repoName}`,
    repoOwner: owner,
    installCommand: `npx skills install ${owner}/${repoName}`,
  }
}
