interface PublishResult {
  repoUrl: string
  repoOwner: string
  installCommand: string
}

interface PublishOptions {
  userName: string
  files: Array<{ path: string; content: string }>
  githubAccessToken?: string
}

export async function publishToGitHub(options: PublishOptions): Promise<PublishResult> {
  const { userName, files, githubAccessToken } = options
  const slug = userName.toLowerCase().replace(/\s+/g, '-')
  const repoName = `acting-as-${slug}`

  if (githubAccessToken) {
    return publishToPersonalRepo(repoName, files, githubAccessToken)
  }

  return {
    repoUrl: `https://github.com/skill-builder-platform/${repoName}`,
    repoOwner: 'skill-builder-platform',
    installCommand: `npx skills install ${slug}`,
  }
}

async function publishToPersonalRepo(
  repoName: string,
  files: Array<{ path: string; content: string }>,
  token: string
): Promise<PublishResult> {
  const userRes = await fetch('https://api.github.com/user', {
    headers: { Authorization: `Bearer ${token}` },
  })
  const user = await userRes.json()
  const owner = user.login

  let repoExists = false
  const checkRes = await fetch(`https://api.github.com/repos/${owner}/${repoName}`, {
    headers: { Authorization: `Bearer ${token}` },
  })
  repoExists = checkRes.ok

  if (!repoExists) {
    await fetch('https://api.github.com/user/repos', {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        name: repoName,
        description: `Professional identity skill generated by Skill Builder`,
        private: false,
        auto_init: true,
      }),
    })
  }

  for (const file of files) {
    const existingRes = await fetch(
      `https://api.github.com/repos/${owner}/${repoName}/contents/${file.path}`,
      { headers: { Authorization: `Bearer ${token}` } }
    )
    const existing = existingRes.ok ? await existingRes.json() : null

    await fetch(
      `https://api.github.com/repos/${owner}/${repoName}/contents/${file.path}`,
      {
        method: 'PUT',
        headers: {
          Authorization: `Bearer ${token}`,
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          message: `Update ${file.path}`,
          content: btoa(file.content),
          sha: existing?.sha,
        }),
      }
    )
  }

  return {
    repoUrl: `https://github.com/${owner}/${repoName}`,
    repoOwner: owner,
    installCommand: `npx skills install ${owner}/${repoName}`,
  }
}
